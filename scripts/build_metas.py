def take(nb_key, idx, must_contain):
    c = copy.deepcopy(src[nb_key]["cells"][idx])
    text = "".join(c["source"])
    assert must_contain in text, f"{nb_key} cell {idx}: expected {must_contain!r}, got: {text[:120]!r}"
    if c["cell_type"] == "code":
        c["outputs"] = []; c["execution_count"] = None
    return c

def md(s):   return {"cell_type": "markdown", "metadata": {}, "source": s.splitlines(keepends=True)}
def code(s): return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
                     "source": s.splitlines(keepends=True)}

