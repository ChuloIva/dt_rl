def cleanup_cell(patterns, default_delete, extra_skip=""):
    pats = json.dumps(patterns, indent=4).replace("    ", "    ")
    return code(f"""\
import fnmatch
DO_DELETE = {default_delete}    # set False on resume re-runs (or for a dry run)

PATTERNS = {pats}
KEEP = {{"frozen_task_ids.json", "manifest.json", "manifest_trainvecs.json"}}

n = 0
for sub, pats in PATTERNS.items():
    d = DRIVE / sub
    if not d.exists():
        continue
    for f in sorted(d.iterdir()):
        if f.name in KEEP or "base" in f.name or not f.is_file(){extra_skip}:
            continue
        if any(fnmatch.fnmatch(f.name, p) for p in pats):
            print(("rm  " if DO_DELETE else "dry ") + str(f))
            if DO_DELETE:
                f.unlink()
            n += 1
print(f"[cleanup] {{n}} files " + ("deleted" if DO_DELETE else "matched (dry run)"))
""")

def write_nb(path, cells):
    nb = {"cells": cells,
          "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                       "language_info": {"name": "python"},
                       "accelerator": "GPU"},
          "nbformat": 4, "nbformat_minor": 5}
    path.write_text(json.dumps(nb, indent=1))
    # validate: compile each code cell (magics/bangs -> pass; allow top-level await)
    for i, c in enumerate(json.loads(path.read_text())["cells"]):
        if c["cell_type"] != "code":
            continue
        body = "\n".join(
            (l[:len(l) - len(l.lstrip())] + "pass") if l.lstrip().startswith(("!", "%")) else l
            for l in "".join(c["source"]).split("\n"))
        try:
            compile(body, f"{path.name}:cell{i}", "exec")
        except SyntaxError:
            compile("async def _w():\n" + "\n".join("    " + l for l in body.split("\n")),
                    f"{path.name}:cell{i}", "exec")
    print(f"wrote {path} ({len(cells)} cells)")

